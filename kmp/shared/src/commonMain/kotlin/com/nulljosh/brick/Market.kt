private val IMPERIAL_AREA: Set<String> = setOf("US", "CA", "GB", "IN", "HK", "SG", "PK", "BD", "MY", "LK", "NP", "GH", "NG")

data class Market(val countryCode: String, val currency: String, val level: Double, val grossYield: Double, val imperial: Boolean)

private val DEFAULT_CURRENCY = "USD"
private const val DEFAULT_LEVEL = 0.5
private const val DEFAULT_YIELD = 0.06

fun marketFor(countryCode: String = ""): Market {
    val cc = countryCode.uppercase()
    return Market(
        countryCode = cc,
        currency = CURRENCIES[cc] ?: DEFAULT_CURRENCY,
        level = PRICE_LEVEL[cc] ?: DEFAULT_LEVEL,
        grossYield = GROSS_YIELD[cc] ?: DEFAULT_YIELD,
        imperial = IMPERIAL_AREA.contains(cc),
    )
}

// ponytail: simple currency-code prefix, not Intl.NumberFormat's locale-aware
// grouping/symbol. Good enough for a list price, not a receipt.
fun formatMoney(amount: Double, currency: String): String {
    val zeroDecimal = setOf("JPY", "KRW", "VND", "IDR", "CLP", "ISK", "HUF", "TWD")
    val rounded = if (currency in zeroDecimal) amount.toLong().toString() else amount.toLong().toString()
    return "$currency $rounded"
}

fun formatArea(sqft: Int, imperial: Boolean): String {
    val value = if (imperial) sqft else (sqft * 0.092903).toInt()
    val unit = if (imperial) "ft\u00b2" else "m\u00b2"
    return "$value $unit"
}
